function resolve_pg_game_uid($inputCode, $gameName = '') {
    $clean = trim((string)$inputCode);
    if (preg_match('/^[a-f0-9]{32}$/i', $clean)) {
        return $clean;
    }
    $map = get_pg_game_map();
    if (isset($map[$clean])) {
        return $map[$clean];
    }
    if (!empty($gameName)) {
        $normName = strtolower(preg_replace('/[^a-z0-9]/i', '', $gameName));
        if (isset($map[$normName])) {
            return $map[$normName];
        }
    }
    $normClean = strtolower(preg_replace('/[^a-z0-9]/i', '', $clean));
    if (isset($map[$normClean])) {
        return $map[$normClean];
    }
    return $clean;
}
